bool get_hex(const toml::table& t, const char* key, Bytes& out, std::string& err, const std::string& where) {
    auto s = t[key].value<std::string>();
    if (!s) return true;
    if (!parse_hex(*s, out)) { err = where + ": `" + key + "` is not valid hex"; return false; }
    return true;
}

toml::value<int64_t> hexval(uint32_t v) {
    toml::value<int64_t> x{int64_t(v)};
    x.flags(toml::value_flags::format_as_hexadecimal);
    return x;
}

