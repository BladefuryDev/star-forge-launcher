bool parse_patchset(const std::string& text, const std::string& source_name, Patchset& out, std::string& err) {
    toml::table root;
    try {
        root = toml::parse(text, source_name);
    } catch (const toml::parse_error& e) {
        std::ostringstream os;
        os << e;
        err = os.str();
        return false;
    }
    if (root["format"].value_or(0) != Patchset::kFormat) {
        err = source_name + ": unsupported patchset format (rebuild with this sfp version)";
        return false;
    }
    out = Patchset{};
    out.exe = root["exe"].value_or(std::string{});
    out.sha1 = root["sha1"].value_or(std::string{});
    out.build = root["build"].value_or(std::string{});
    out.image_base = uint32_t(root["image_base"].value_or(int64_t(0)));
    if (out.exe.empty() || out.sha1.size() != 40) { err = source_name + ": missing exe/sha1"; return false; }
    if (auto arr = root["patch"].as_array()) {
        for (auto& pe : *arr) {
            auto pt = pe.as_table();
            if (!pt) continue;
            Patch p;
            p.id = (*pt)["id"].value_or(std::string{});
            p.title = (*pt)["title"].value_or(std::string{});
            p.description = (*pt)["description"].value_or(std::string{});
            p.enabled_by_default = (*pt)["default"].value_or(true);
            p.optional = (*pt)["optional"].value_or(false);
            std::string where = source_name + ": patch '" + p.id + "'";
            if (p.id.empty()) { err = source_name + ": patch without id"; return false; }
            if (auto ws = (*pt)["write"].as_array()) {
                for (auto& we : *ws) {
                    auto wt = we.as_table();
                    if (!wt) continue;
                    Write w;
                    w.va = uint32_t((*wt)["va"].value_or(int64_t(0)));
                    w.midhook = (*wt)["midhook"].value_or(std::string{});
                    w.comment = (*wt)["comment"].value_or(std::string{});
                    if (!get_hex(*wt, "orig", w.orig, err, where) || !get_hex(*wt, "bytes", w.bytes, err, where)) return false;
                    if (!w.va || w.orig.empty()) { err = where + ": write needs va and orig"; return false; }
                    if (w.midhook.empty() && w.bytes.size() != w.orig.size()) {
                        err = where + ": write at " + hex32(w.va) + " has orig/bytes of different length";
                        return false;
                    }
                    p.writes.push_back(std::move(w));
                }
            }
            out.patches.push_back(std::move(p));
        }
    }
    return true;
}

std::string format_patchset(const Patchset& ps) {
    toml::table root;
    root.insert("format", Patchset::kFormat);
    root.insert("exe", ps.exe);
    root.insert("sha1", ps.sha1);
    if (!ps.build.empty()) root.insert("build", ps.build);
    root.insert("image_base", hexval(ps.image_base));
    toml::array patches;
    for (auto& p : ps.patches) {
        toml::table pt;
        pt.insert("id", p.id);
        if (!p.title.empty()) pt.insert("title", p.title);
        if (!p.description.empty()) pt.insert("description", p.description);
        pt.insert("default", p.enabled_by_default);
        pt.insert("optional", p.optional);
        toml::array writes;
        for (auto& w : p.writes) {
            toml::table wt;
            wt.insert("va", hexval(w.va));
            wt.insert("orig", to_hex(w.orig));
            if (w.midhook.empty()) wt.insert("bytes", to_hex(w.bytes));
            else wt.insert("midhook", w.midhook);
            if (!w.comment.empty()) wt.insert("comment", w.comment);
            writes.push_back(std::move(wt));
        }
        pt.insert("write", std::move(writes));
        patches.push_back(std::move(pt));
    }
    root.insert("patch", std::move(patches));
    std::ostringstream os;
    os << "# Generated by `sfp build` -- do not edit. Sources: <project>/" << ps.exe << "/\n" << root << "\n";
    return os.str();
}

bool parse_config(const std::string& text, const std::string& source_name, Config& out, std::string& err) {
    toml::table root;
    try {
        root = toml::parse(text, source_name);
    } catch (const toml::parse_error& e) {
        std::ostringstream os;
        os << e;
        err = os.str();
        return false;
    }
    out = Config{};
    std::string on_error = root["on_error"].value_or(std::string("exit"));
    if (on_error != "exit" && on_error != "continue") { err = source_name + ": on_error must be \"exit\" or \"continue\""; return false; }
    out.exit_on_error = on_error == "exit";
    if (auto t = root["patches"].as_table()) {
        for (auto& [exe, sub] : *t) {
            auto st = sub.as_table();
            if (!st) { err = source_name + ": [patches] entries must be per-exe tables, e.g. [patches.\"Shard.exe\"]"; return false; }
            for (auto& [k, v] : *st) {
                auto b = v.value<bool>();
                if (!b) {
                    err = source_name + ": [patches.\"" + std::string(exe.str()) + "\"] " + std::string(k.str()) + " must be true or false";
                    return false;
                }
                out.overrides[std::string(exe.str())][std::string(k.str())] = *b;
            }
        }
    }
    return true;
}

std::vector<const Patch*> enabled_patches(const Patchset& ps, const Config& cfg, std::vector<std::string>& warnings) {
    std::vector<const Patch*> on;
    static const std::map<std::string, bool> none;
    auto ov = cfg.overrides.find(ps.exe);
    const auto& mine = ov != cfg.overrides.end() ? ov->second : none;
    for (auto& kv : mine) {
        const std::string& id = kv.first;
        bool known = std::any_of(ps.patches.begin(), ps.patches.end(), [&](const Patch& p) { return p.id == id; });
        if (!known) warnings.push_back("config mentions unknown patch '" + id + "' for " + ps.exe);
    }
    for (auto& p : ps.patches) {
        auto it = mine.find(p.id);
        if (it != mine.end() ? it->second : p.enabled_by_default) on.push_back(&p);
    }
    return on;
}

std::vector<std::string> find_overlaps(const std::vector<const Patch*>& patches) {
    struct R { uint32_t lo, hi; const Patch* p; };
    std::vector<R> rs;
    for (auto p : patches)
        for (auto& w : p->writes) rs.push_back({w.va, w.va + uint32_t(w.orig.size()), p});
    std::sort(rs.begin(), rs.end(), [](const R& a, const R& b) { return a.lo < b.lo; });
    std::vector<std::string> errs;
    for (size_t i = 0; i < rs.size(); i++)
        for (size_t j = i + 1; j < rs.size() && rs[j].lo < rs[i].hi; j++)
            errs.push_back("'" + rs[i].p->id + "' and '" + rs[j].p->id + "' both write " + hex32(rs[j].lo) + ".." +
                           hex32(std::min(rs[i].hi, rs[j].hi)));
    return errs;
}

